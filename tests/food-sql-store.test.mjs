test('SQL store serializes every write on settings row before reads and always rolls back/releases on error',async()=>{
 assert.equal(typeof module.createFoodStore,'function');
 const log=[];
 const connection={async beginTransaction(){log.push('begin');},async execute(sql,args){log.push({sql,args});return [[{id:1,config:'{"order_accepting":false}'}]];},async commit(){log.push('commit');},async rollback(){log.push('rollback');},release(){log.push('release');}};
 const store=module.createFoodStore({async getConnection(){return connection;}});
 const config=await store.withTransaction(async tx=>tx.getSettings());
 assert.equal(config.order_accepting,false);
 assert.equal(log[0],'begin');
 assert.match(log[1].sql,/food_settings.*FOR UPDATE/s);
 assert.equal(log.at(-2),'commit');assert.equal(log.at(-1),'release');
 log.length=0;
 await assert.rejects(store.withTransaction(async()=>{throw Error('failed');}),/failed/);
 assert.equal(log.at(-2),'rollback');assert.equal(log.at(-1),'release');
});
